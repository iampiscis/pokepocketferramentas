export function corrigirNiveisDeEvolucao(lista) {
  let corrigidos = 0;
  for (const c of lista) {
    const nivel = NIVEIS_POR_ONDE_O_ALVO_APARECE[c.pokeId];
    if (!nivel || !c.evolvesToId || c.evolveLevel === nivel) continue;
    c.evolveLevel = nivel;
    corrigidos++;
  }
  return corrigidos;
}













